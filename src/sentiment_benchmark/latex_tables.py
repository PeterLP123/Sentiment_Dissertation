"""Dissertation-ready booktabs LaTeX tables for a benchmark run.

Tables are generated from already-parsed metric/statistics structures (not the
database), mirroring :mod:`sentiment_benchmark.plotting`. Each ``.tex`` file is a
standalone ``table`` environment with a caption, a label, and a provenance
comment header recording the run id, dataset hash, and prompt hash, so a table
can be ``\\input{}`` into the dissertation and later traced back to the exact
run that produced it. The only LaTeX package required is ``booktabs``.

Files produced (when the underlying data is present):

* ``leaderboard.tex`` — model ranking with bootstrap CIs; best values bold.
* ``per_class.tex`` — per-model precision/recall/F1/support by class.
* ``mcnemar.tex`` — pairwise McNemar tests with significance markers.
* ``agreement.tex`` — inter-model agreement statistics.
* ``operational.tex`` — cost, latency percentiles, tokens, and failure rates.
* ``tables.tex`` — master file that ``\\input``s every table written.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .constants import ALLOWED_LABELS

_LATEX_SPECIALS = (
    ("&", r"\&"),
    ("%", r"\%"),
    ("$", r"\$"),
    ("#", r"\#"),
    ("_", r"\_"),
    ("{", r"\{"),
    ("}", r"\}"),
    ("~", r"\textasciitilde{}"),
    ("^", r"\textasciicircum{}"),
)


def latex_escape(text: str) -> str:
    """Escape LaTeX special characters in plain text (model ids, prompt ids)."""
    # Stash backslashes first so the braces of their own replacement are not re-escaped.
    text = text.replace("\\", "\x00")
    for char, replacement in _LATEX_SPECIALS:
        text = text.replace(char, replacement)
    return text.replace("\x00", r"\textbackslash{}")


def _num(value: Any, decimals: int = 3) -> str:
    if not isinstance(value, (int, float)):
        return "--"
    return f"{float(value):.{decimals}f}"


def _pct(value: Any) -> str:
    if not isinstance(value, (int, float)):
        return "--"
    return f"{float(value) * 100.0:.1f}"


def _cost(value: Any) -> str:
    """Format a USD amount, keeping precision for sub-cent per-run totals."""
    if not isinstance(value, (int, float)):
        return "--"
    amount = float(value)
    return f"{amount:,.2f}" if abs(amount) >= 0.1 else f"{amount:.4f}"


def _p_value(p: Any) -> str:
    if not isinstance(p, (int, float)):
        return "--"
    p = float(p)
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}"


def _stars(p: Any) -> str:
    if not isinstance(p, (int, float)):
        return ""
    p = float(p)
    if p < 0.001:
        return r"$^{***}$"
    if p < 0.01:
        return r"$^{**}$"
    if p < 0.05:
        return r"$^{*}$"
    return ""


def _bold_if(text: str, condition: bool) -> str:
    return rf"\textbf{{{text}}}" if condition else text


def _is_best(value: Any, best: float | None) -> bool:
    return isinstance(value, (int, float)) and best is not None and abs(float(value) - best) < 1e-12


def _column_max(records: list[dict[str, Any]], key: str) -> float | None:
    values = [float(record[key]) for record in records if isinstance(record.get(key), (int, float))]
    return max(values) if values else None


def provenance_header(metadata: dict[str, Any], run_id: int) -> str:
    """Comment block tying a table file back to the run that produced it."""
    dataset_sha = str(metadata.get("dataset_sha256") or "unknown")[:12]
    lines = [
        f"% Auto-generated by sentiment-dissertation-benchmark v{metadata.get('package_version', '?')}"
        " -- do not edit by hand.",
        f"% Run {run_id} | mode {metadata.get('mode', '?')} | exported {metadata.get('exported_at', '?')}",
        f"% Dataset {metadata.get('dataset_path', '?')} | sha256 {dataset_sha}",
        f"% Prompt hash {metadata.get('prompt_hash', '?')}",
        "% Requires \\usepackage{booktabs} in the document preamble.",
    ]
    return "\n".join(lines)


def _table_env(
    caption: str,
    label: str,
    column_spec: str,
    header: str,
    body_lines: list[str],
    notes: str | None = None,
) -> str:
    parts = [
        r"\begin{table}[htbp]",
        r"  \centering",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        r"  \small",
        f"  \\begin{{tabular}}{{{column_spec}}}",
        r"    \toprule",
        f"    {header} \\\\",
        r"    \midrule",
    ]
    parts.extend(f"    {line}" for line in body_lines)
    parts.extend([r"    \bottomrule", r"  \end{tabular}"])
    if notes:
        parts.extend([r"  \par\smallskip", rf"  \raggedright\footnotesize {notes}"])
    parts.append(r"\end{table}")
    return "\n".join(parts)


def _metrics_for_scope(metric_records: list[dict[str, Any]], scope: str) -> list[dict[str, Any]]:
    rows = [record for record in metric_records if record.get("scope") == scope]
    rows.sort(key=lambda record: (-float(record.get("macro_f1", 0.0)), str(record.get("model_id"))))
    return rows


def leaderboard_table(
    metric_records: list[dict[str, Any]],
    statistics: dict[str, Any],
    run_id: int,
    scope: str = "primary",
) -> str | None:
    """Model ranking with bootstrap CIs where available; best value per column bold."""
    records = _metrics_for_scope(metric_records, scope)
    if not records:
        return None
    per_model = statistics.get("per_model") or {}

    confidence = 95
    for model_stats in per_model.values():
        ci = model_stats.get("accuracy_ci") or {}
        if isinstance(ci.get("confidence"), (int, float)):
            confidence = round(float(ci["confidence"]) * 100)
            break

    best = {key: _column_max(records, key) for key in ("accuracy", "macro_f1", "balanced_accuracy", "mcc")}

    def _point_with_ci(record: dict[str, Any], metric_key: str, ci_key: str) -> str:
        point = _bold_if(_num(record.get(metric_key)), _is_best(record.get(metric_key), best[metric_key]))
        ci = (per_model.get(str(record["model_id"])) or {}).get(ci_key) or {}
        if isinstance(ci.get("lower"), (int, float)) and isinstance(ci.get("upper"), (int, float)):
            return f"{point} [{_num(ci['lower'])}, {_num(ci['upper'])}]"
        return point

    body = []
    for record in records:
        cells = [
            latex_escape(str(record["model_id"])),
            str(int(record.get("row_count", 0))),
            _point_with_ci(record, "accuracy", "accuracy_ci"),
            _point_with_ci(record, "macro_f1", "macro_f1_ci"),
            _bold_if(_num(record.get("balanced_accuracy")), _is_best(record.get("balanced_accuracy"), best["balanced_accuracy"])),
            _bold_if(_num(record.get("mcc")), _is_best(record.get("mcc"), best["mcc"])),
            str(int(record.get("invalid_output_count", 0))),
            str(int(record.get("api_error_count", 0))),
        ]
        body.append(" & ".join(cells) + r" \\")

    caption = (
        f"Classification performance on run {run_id} ({scope} scope), sorted by macro-F1. "
        f"Accuracy and macro-F1 show {confidence}\\% bootstrap confidence intervals where available; "
        "the best value in each metric column is bold. "
        "Invalid: outputs that could not be parsed into a label; Err.: failed API requests."
    )
    header = r"Model & $n$ & Accuracy & Macro-F1 & Bal.\ acc. & MCC & Invalid & Err."
    return _table_env(caption, f"tab:leaderboard-run{run_id}", "lrllrrrr", header, body)


def per_class_table(metric_records: list[dict[str, Any]], run_id: int, scope: str = "primary") -> str | None:
    """Per-model precision/recall/F1/support by class, one block per model."""
    records = _metrics_for_scope(metric_records, scope)
    records = [record for record in records if record.get("per_class")]
    if not records:
        return None

    body: list[str] = []
    for index, record in enumerate(records):
        if index:
            body.append(r"\addlinespace")
        per_class = record["per_class"]
        for position, label in enumerate(ALLOWED_LABELS):
            scores = per_class.get(label) or {}
            cells = [
                latex_escape(str(record["model_id"])) if position == 0 else "",
                label,
                _num(scores.get("precision")),
                _num(scores.get("recall")),
                _num(scores.get("f1")),
                str(int(scores.get("support", 0))),
            ]
            body.append(" & ".join(cells) + r" \\")

    caption = (
        f"Per-class precision, recall, and F1 for run {run_id} ({scope} scope). "
        "Support is the number of gold-label rows per class in the evaluated selection."
    )
    header = "Model & Class & Precision & Recall & F1 & Support"
    return _table_env(caption, f"tab:per-class-run{run_id}", "llrrrr", header, body)


def mcnemar_table(statistics: dict[str, Any], run_id: int) -> str | None:
    """Pairwise McNemar tests with significance markers (uncorrected)."""
    pairwise = statistics.get("pairwise_mcnemar") or []
    if not pairwise:
        return None

    body = []
    for pair in pairwise:
        cells = [
            latex_escape(str(pair["model_a"])),
            latex_escape(str(pair["model_b"])),
            str(int(pair.get("n", 0))),
            str(int(pair.get("b_a_correct_b_wrong", 0))),
            str(int(pair.get("c_a_wrong_b_correct", 0))),
            f"{_p_value(pair.get('p_value'))}{_stars(pair.get('p_value'))}",
            str(pair.get("method", "")).replace("_", r"\_"),
        ]
        body.append(" & ".join(cells) + r" \\")

    caption = (
        f"Pairwise McNemar tests on the shared rows of run {run_id} (primary scope). "
        "$b$: rows only model A classified correctly; $c$: rows only model B classified correctly."
    )
    header = "Model A & Model B & $n$ & $b$ & $c$ & $p$-value & Method"
    notes = (
        r"$^{*}p<0.05$; $^{**}p<0.01$; $^{***}p<0.001$ (two-sided, "
        "uncorrected for multiple comparisons)."
    )
    return _table_env(caption, f"tab:mcnemar-run{run_id}", "llrrrrl", header, body, notes=notes)


def agreement_table(statistics: dict[str, Any], run_id: int) -> str | None:
    """Inter-model agreement summary plus pairwise Cohen's kappa."""
    agreement = statistics.get("agreement")
    if not agreement:
        return None

    body = [
        f"Raters (models) & {int(agreement.get('n_raters', 0))} \\\\",
        f"Items rated by all models & {int(agreement.get('n_units_all_raters', 0))} \\\\",
        f"Mean pairwise observed agreement & {_num(agreement.get('observed_agreement'))} \\\\",
        f"Fleiss' $\\kappa$ & {_num(agreement.get('fleiss_kappa'))} \\\\",
        f"Krippendorff's $\\alpha$ (nominal) & {_num(agreement.get('krippendorff_alpha'))} \\\\",
    ]
    pairwise = agreement.get("pairwise_cohen_kappa") or []
    if pairwise:
        body.append(r"\midrule")
        body.append(r"\multicolumn{2}{l}{\itshape Pairwise Cohen's $\kappa$} \\")
        for pair in pairwise:
            name = f"{latex_escape(str(pair['rater_a']))} vs.\\ {latex_escape(str(pair['rater_b']))}"
            body.append(f"{name} & {_num(pair.get('kappa'))} ($n$ = {int(pair.get('n', 0))}) \\\\")

    caption = (
        f"Inter-model agreement on run {run_id} (primary scope, valid predictions only). "
        "Chance-corrected statistics near 0 indicate agreement no better than chance; 1 is perfect agreement."
    )
    header = "Statistic & Value"
    return _table_env(caption, f"tab:agreement-run{run_id}", "lr", header, body)


def operational_table(statistics: dict[str, Any], run_id: int) -> str | None:
    """Cost, latency percentiles, token usage, and failure rates per model."""
    per_model = (statistics.get("operational") or {}).get("per_model") or {}
    if not per_model:
        return None

    body = []
    for model_id in sorted(per_model):
        entry = per_model[model_id]
        latency = entry.get("latency_ms") or {}
        cost = entry.get("cost") or {}
        tokens = entry.get("tokens") or {}
        cells = [
            latex_escape(model_id),
            _cost(cost.get("total_usd")),
            _cost(cost.get("usd_per_1k_rows")),
            _num(latency.get("p50"), 0),
            _num(latency.get("p95"), 0),
            _num(tokens.get("mean_total_per_row"), 1),
            _pct(entry.get("invalid_rate")),
            _pct(entry.get("api_error_rate")),
        ]
        body.append(" & ".join(cells) + r" \\")

    caption = (
        f"Operational characteristics of run {run_id}, over every attempted row in the run. "
        "Latency percentiles are per-request. Cost figures rely on provider-reported generation "
        "metadata and are unavailable (--) for baselines and local models."
    )
    header = (
        r"Model & Cost (\$) & \$/1k rows & p50 (ms) & p95 (ms) & Tok./row & "
        r"Invalid (\%) & Err.\ (\%)"
    )
    return _table_env(caption, f"tab:operational-run{run_id}", "lrrrrrrr", header, body)


def sensitivity_table_latex(result: Any) -> str:
    """Prompt-sensitivity table for one model across a prompt-variant family.

    ``result`` is a :class:`sentiment_benchmark.prompt_sensitivity.SensitivityResult`.
    Values use four decimals because prompt-induced spreads are often small.
    """
    metric_name = str(result.metric).replace("_", " ").title()
    body = []
    for variant in sorted(result.variants, key=lambda item: item.value, reverse=True):
        body.append(
            f"{latex_escape(variant.prompt_id)} & {int(variant.run_id)} & {_num(variant.value, 4)} \\\\"
        )
    body.append(r"\midrule")
    for name, value in (
        ("Mean", result.mean),
        ("Std.\\ dev.", result.std),
        ("Minimum", result.minimum),
        ("Maximum", result.maximum),
        ("Spread (max $-$ min)", result.spread),
        ("Coefficient of variation", result.cv),
    ):
        body.append(rf"\multicolumn{{2}}{{l}}{{{name}}} & {_num(value, 4)} \\")

    caption = (
        f"Prompt sensitivity of {latex_escape(result.model_id)}: {metric_name.lower()} across "
        f"{result.n} prompt variants ({result.scope} scope). Each variant evaluates the same "
        "seeded row selection, so the spread quantifies prompt-design fragility."
    )
    header = f"Prompt variant & Run & {metric_name}"
    table = _table_env(
        caption,
        f"tab:prompt-sensitivity-{result.model_id.replace('/', '-').replace('_', '-')}",
        "lrr",
        header,
        body,
    )
    preamble = "% Requires \\usepackage{booktabs} in the document preamble.\n"
    return preamble + table + "\n"


def generate_latex_tables(
    metric_records: list[dict[str, Any]],
    statistics: dict[str, Any],
    metadata: dict[str, Any],
    run_id: int,
    output_dir: str | Path,
    scope: str = "primary",
) -> list[Path]:
    """Write booktabs tables for a run and return the paths created.

    Returns an empty list when there is nothing to tabulate. Each file carries a
    provenance header; ``tables.tex`` ``\\input``s every table that was written.
    """
    tables: list[tuple[str, str | None]] = [
        ("leaderboard.tex", leaderboard_table(metric_records, statistics, run_id, scope)),
        ("per_class.tex", per_class_table(metric_records, run_id, scope)),
        ("mcnemar.tex", mcnemar_table(statistics, run_id)),
        ("agreement.tex", agreement_table(statistics, run_id)),
        ("operational.tex", operational_table(statistics, run_id)),
    ]
    available = [(name, content) for name, content in tables if content is not None]
    if not available:
        return []

    destination = Path(output_dir)
    destination.mkdir(parents=True, exist_ok=True)
    header = provenance_header(metadata, run_id)

    paths: list[Path] = []
    for name, content in available:
        path = destination / name
        path.write_text(f"{header}\n{content}\n", encoding="utf-8")
        paths.append(path)

    master_lines = [
        header,
        "% Master include for this run's tables. \\input paths resolve relative to the",
        "% directory you compile from; adjust them if you copy these files elsewhere.",
        *(f"\\input{{{name}}}" for name, _ in available),
    ]
    master = destination / "tables.tex"
    master.write_text("\n".join(master_lines) + "\n", encoding="utf-8")
    paths.append(master)
    return paths
